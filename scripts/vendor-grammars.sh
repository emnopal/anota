#!/bin/bash
# Re-vendors tree-sitter grammars (generated C only, from release tarballs: no git history) into
# Vendor/TreeSitterGrammars, and their highlight queries into Sources/AnotaCore/Queries.
# Why vendored: SwiftPM clones full histories (TypeScript 143 MB, C++ 97 MB, …) and several
# upstream manifests drop their external scanner (fileExists bug), which fails at link time.
# Usage: scripts/vendor-grammars.sh   (bump versions in the table below, rerun, run `swift test`)
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=Vendor/TreeSitterGrammars
Q=Sources/AnotaCore/Queries
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

rm -rf "$OUT" && mkdir -p "$OUT/include" "$OUT/LICENSES" "$Q"
rm -f "$Q"/*.scm

fetch() {  # repo tag [url strip] -> extracted dir
    local dir="$TMP/${1//\//_}"
    mkdir -p "$dir"
    curl -fsSL "${3:-https://codeload.github.com/$1/tar.gz/refs/tags/$2}" | tar xz -C "$dir" --strip-components "${4:-1}"
    echo "$dir"
}

grammar() {  # name src-dir license-file [dest-subdir]
    local dest="$OUT/$1/${4:-src}"
    mkdir -p "$dest"
    cp "$2"/*.c "$dest/"
    cp -R "$2/tree_sitter" "$dest/"
    rm -f "$dest"/parser_abi*.c
    cp "$3" "$OUT/LICENSES/$1.txt"
}

query() {  # out-name file...  (concatenated: C++ extends C, TypeScript extends JavaScript)
    local name=$1; shift
    cat "$@" > "$Q/$name.scm"
}

d=$(fetch tree-sitter/tree-sitter-json v0.24.8);              grammar json "$d/src" "$d/LICENSE";       query json "$d/queries/highlights.scm"
d=$(fetch tree-sitter-grammars/tree-sitter-yaml v0.7.2);      grammar yaml "$d/src" "$d/LICENSE";       query yaml "$d/queries/highlights.scm"
d=$(fetch tree-sitter-grammars/tree-sitter-toml v0.7.0);      grammar toml "$d/src" "$d/LICENSE";       query toml "$d/queries/highlights.scm"
d=$(fetch justinmk/tree-sitter-ini v1.4.0);                   grammar ini "$d/src" "$d/LICENSE";        query ini "$d/queries/highlights.scm"
d=$(fetch tree-sitter/tree-sitter-python v0.25.0);            grammar python "$d/src" "$d/LICENSE";     query python "$d/queries/highlights.scm"
js=$(fetch tree-sitter/tree-sitter-javascript v0.25.0);       grammar javascript "$js/src" "$js/LICENSE"
query javascript "$js/queries/highlights.scm" "$js/queries/highlights-jsx.scm"
d=$(fetch tree-sitter/tree-sitter-typescript v0.23.2)
grammar typescript "$d/typescript/src" "$d/LICENSE" typescript/src
grammar typescript "$d/tsx/src" "$d/LICENSE" tsx/src
cp -R "$d/common" "$OUT/typescript/common"  # scanner.c includes ../../common/scanner.h
cp -R "$d/typescript/src/tree_sitter" "$OUT/typescript/common/"  # …which includes tree_sitter/parser.h
query typescript "$js/queries/highlights.scm" "$d/queries/highlights.scm"
query tsx "$js/queries/highlights.scm" "$js/queries/highlights-jsx.scm" "$d/queries/highlights.scm"
d=$(fetch tree-sitter/tree-sitter-go v0.25.0);                grammar go "$d/src" "$d/LICENSE";         query go "$d/queries/highlights.scm"
c=$(fetch tree-sitter/tree-sitter-c v0.24.2);                 grammar c "$c/src" "$c/LICENSE";          query c "$c/queries/highlights.scm"
d=$(fetch tree-sitter/tree-sitter-cpp v0.23.4);               grammar cpp "$d/src" "$d/LICENSE";        query cpp "$c/queries/highlights.scm" "$d/queries/highlights.scm"
d=$(fetch tree-sitter/tree-sitter-rust v0.24.2);              grammar rust "$d/src" "$d/LICENSE";       query rust "$d/queries/highlights.scm"
# Swift's generated parser only ships in the release asset, not in the tagged source.
d=$(fetch alex-pinkus/tree-sitter-swift 0.7.3 https://github.com/alex-pinkus/tree-sitter-swift/releases/download/0.7.3/tree-sitter-swift.tar.gz 0)
grammar swift "$d/src" "$d/LICENSE";                          query swift "$d/queries/highlights.scm"

# Local query fixes (marked "; Anota:").
perl -0pi -e 's/\(pair\n  \(bare_key\)\) \@property/(pair\n  (bare_key) \@property) ; Anota: capture the key, not the whole pair/' "$Q/toml.scm"

cat > "$OUT/include/tree_sitter_grammars.h" <<'EOF'
#ifndef TREE_SITTER_GRAMMARS_H
#define TREE_SITTER_GRAMMARS_H
typedef struct TSLanguage TSLanguage;
const TSLanguage *tree_sitter_json(void);
const TSLanguage *tree_sitter_yaml(void);
const TSLanguage *tree_sitter_toml(void);
const TSLanguage *tree_sitter_ini(void);
const TSLanguage *tree_sitter_python(void);
const TSLanguage *tree_sitter_javascript(void);
const TSLanguage *tree_sitter_typescript(void);
const TSLanguage *tree_sitter_tsx(void);
const TSLanguage *tree_sitter_go(void);
const TSLanguage *tree_sitter_c(void);
const TSLanguage *tree_sitter_cpp(void);
const TSLanguage *tree_sitter_rust(void);
const TSLanguage *tree_sitter_swift(void);
#endif
EOF
printf 'Generated by scripts/vendor-grammars.sh (do not edit by hand). Each grammar keeps its own\nsrc/tree_sitter headers; licenses (all MIT) in LICENSES/. Versions: see the script.\n' > "$OUT/README.md"
printf 'Generated by scripts/vendor-grammars.sh: highlights.scm per grammar (C++ = C + C++,\nTypeScript/TSX = JavaScript + TypeScript). Local fixes are applied by the script and marked "; Anota:".\n' > "$Q/README.md"
chmod -R u+w "$OUT" "$Q"
find "$OUT" -name '*.c' | sort
du -sh "$OUT"
